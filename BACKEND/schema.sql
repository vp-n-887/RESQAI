-- Fresh-install schema. For an existing database, review and apply
-- migrations/001_supabase_schema.sql instead of dropping or recreating tables.

CREATE TABLE ambulances (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_number VARCHAR(20) NOT NULL,
    location VARCHAR(100) NOT NULL,
    latitude DECIMAL(10, 6),
    longitude DECIMAL(10, 6),
    status VARCHAR(20) NOT NULL,
    ambulance_type VARCHAR(20) NOT NULL,
    equipment TEXT
);

CREATE TABLE hospitals (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    location VARCHAR(100) NOT NULL,
    latitude DECIMAL(10, 6),
    longitude DECIMAL(10, 6),
    trauma_care VARCHAR(10),
    icu_available VARCHAR(10),
    available_beds INTEGER,
    specialties TEXT,
    status VARCHAR(20),
    total_rooms INTEGER,
    available_rooms INTEGER,
    CONSTRAINT hospitals_total_rooms_nonnegative
        CHECK (total_rooms IS NULL OR total_rooms >= 0),
    CONSTRAINT hospitals_available_rooms_nonnegative
        CHECK (available_rooms IS NULL OR available_rooms >= 0),
    CONSTRAINT hospitals_available_rooms_within_total
        CHECK (
            total_rooms IS NULL OR available_rooms IS NULL
            OR available_rooms <= total_rooms
        )
);

CREATE TABLE emergencies (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emergency_type VARCHAR(50) NOT NULL,
    location VARCHAR(100) NOT NULL,
    latitude DECIMAL(10, 6),
    longitude DECIMAL(10, 6),
    patient_count INTEGER,
    description TEXT,
    priority VARCHAR(20),
    status VARCHAR(20),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE assignments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emergency_id INTEGER NOT NULL UNIQUE
        REFERENCES emergencies(id) ON DELETE RESTRICT,
    ambulance_id INTEGER NOT NULL
        REFERENCES ambulances(id) ON DELETE RESTRICT,
    hospital_id INTEGER NOT NULL
        REFERENCES hospitals(id) ON DELETE RESTRICT,
    ambulance_eta INTEGER NOT NULL,
    hospital_eta INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX ambulances_status_idx ON ambulances(status);
CREATE INDEX hospitals_availability_idx ON hospitals(status, available_beds);
CREATE INDEX assignments_ambulance_id_idx ON assignments(ambulance_id);
CREATE INDEX assignments_hospital_id_idx ON assignments(hospital_id);
