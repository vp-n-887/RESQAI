-- Non-destructive migration for the schema previously defined in schema.sql.
-- Run the preflight queries in SUPABASE_SETUP.md first. This migration checks
-- existing columns and ID types before making additive changes.

DO $$
DECLARE
    v_table_name TEXT;
    required_columns TEXT[];
    expected_types TEXT[];
    missing_columns TEXT[];
    has_id_primary_key BOOLEAN;
    id_type TEXT;
    identity_kind TEXT;
    id_default TEXT;
BEGIN
    FOREACH v_table_name IN ARRAY ARRAY[
        'ambulances', 'hospitals', 'emergencies', 'assignments'
    ] LOOP
        IF to_regclass(format('public.%I', v_table_name)) IS NOT NULL THEN
            required_columns := CASE v_table_name
                WHEN 'ambulances' THEN ARRAY[
                    'id', 'vehicle_number', 'location', 'latitude', 'longitude',
                    'status', 'ambulance_type', 'equipment'
                ]
                WHEN 'hospitals' THEN ARRAY[
                    'id', 'name', 'location', 'latitude', 'longitude',
                    'trauma_care', 'icu_available', 'available_beds',
                    'specialties', 'status'
                ]
                WHEN 'emergencies' THEN ARRAY[
                    'id', 'emergency_type', 'location', 'latitude', 'longitude',
                    'patient_count', 'description', 'priority', 'status'
                ]
                ELSE ARRAY[
                    'id', 'emergency_id', 'ambulance_id', 'hospital_id',
                    'ambulance_eta', 'hospital_eta', 'status'
                ]
            END;
            expected_types := CASE v_table_name
                WHEN 'ambulances' THEN ARRAY[
                    'integer', 'character varying', 'character varying',
                    'numeric', 'numeric', 'character varying',
                    'character varying', 'text'
                ]
                WHEN 'hospitals' THEN ARRAY[
                    'integer', 'character varying', 'character varying',
                    'numeric', 'numeric', 'character varying',
                    'character varying', 'integer', 'text', 'character varying'
                ]
                WHEN 'emergencies' THEN ARRAY[
                    'integer', 'character varying', 'character varying',
                    'numeric', 'numeric', 'integer', 'text',
                    'character varying', 'character varying'
                ]
                ELSE ARRAY[
                    'integer', 'integer', 'integer', 'integer',
                    'integer', 'integer', 'character varying'
                ]
            END;

            SELECT ARRAY(
                SELECT required_column
                FROM unnest(required_columns) AS required_column
                WHERE NOT EXISTS (
                    SELECT 1
                    FROM information_schema.columns AS existing_column
                    WHERE existing_column.table_schema = 'public'
                      AND existing_column.table_name = v_table_name
                      AND existing_column.column_name = required_column
                )
            ) INTO missing_columns;

            IF cardinality(missing_columns) > 0 THEN
                RAISE EXCEPTION
                    'Existing public.% is missing required columns: %; review the schema manually',
                    v_table_name, array_to_string(missing_columns, ', ');
            END IF;

            IF EXISTS (
                SELECT 1
                FROM unnest(required_columns, expected_types)
                    AS expected(column_name, data_type)
                JOIN information_schema.columns AS existing_column
                  ON existing_column.table_schema = 'public'
                 AND existing_column.table_name = v_table_name
                 AND existing_column.column_name = expected.column_name
                WHERE existing_column.data_type <> expected.data_type
            ) THEN
                RAISE EXCEPTION
                    'Existing public.% has incompatible column types; review the schema manually',
                    v_table_name;
            END IF;

            SELECT data_type, is_identity, column_default
            INTO id_type, identity_kind, id_default
            FROM information_schema.columns
            WHERE table_schema = 'public'
              AND information_schema.columns.table_name = v_table_name
              AND column_name = 'id';

            IF id_type <> 'integer' THEN
                RAISE EXCEPTION
                    'public.%.id must be an integer type, found %; review the schema manually',
                    v_table_name, id_type;
            END IF;

            IF identity_kind = 'NO' AND id_default IS NULL THEN
                EXECUTE format(
                    'ALTER TABLE public.%I ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY',
                    v_table_name
                );
            END IF;

            SELECT EXISTS (
                SELECT 1
                FROM pg_constraint
                WHERE conrelid = to_regclass(format('public.%I', v_table_name))
                  AND contype = 'p'
                  AND conkey = ARRAY[
                      (SELECT attnum
                       FROM pg_attribute
                       WHERE attrelid = to_regclass(format('public.%I', v_table_name))
                         AND attname = 'id')
                  ]::smallint[]
            ) INTO has_id_primary_key;

            IF NOT has_id_primary_key THEN
                IF EXISTS (
                    SELECT 1
                    FROM pg_constraint
                    WHERE conrelid = to_regclass(format('public.%I', v_table_name))
                      AND contype = 'p'
                ) THEN
                    RAISE EXCEPTION
                        'Existing public.% has a primary key other than id; review the schema manually',
                        v_table_name;
                END IF;
                EXECUTE format(
                    'ALTER TABLE public.%I ADD PRIMARY KEY (id)',
                    v_table_name
                );
            END IF;
        END IF;
    END LOOP;

    IF EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name IN ('emergencies', 'assignments')
          AND column_name = 'created_at'
          AND data_type <> 'timestamp with time zone'
    ) THEN
        RAISE EXCEPTION
            'Existing created_at columns must be TIMESTAMPTZ; review the schema manually';
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.ambulances (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_number VARCHAR(20) NOT NULL,
    location VARCHAR(100) NOT NULL,
    latitude DECIMAL(10, 6),
    longitude DECIMAL(10, 6),
    status VARCHAR(20) NOT NULL,
    ambulance_type VARCHAR(20) NOT NULL,
    equipment TEXT
);

CREATE TABLE IF NOT EXISTS public.hospitals (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    location VARCHAR(100) NOT NULL,
    latitude DECIMAL(10, 6),
    longitude DECIMAL(10, 6),
    trauma_care VARCHAR(10),
    icu_available VARCHAR(10),
    available_beds INTEGER,
    specialties TEXT,
    status VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS public.emergencies (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emergency_type VARCHAR(50) NOT NULL,
    location VARCHAR(100) NOT NULL,
    latitude DECIMAL(10, 6),
    longitude DECIMAL(10, 6),
    patient_count INTEGER,
    description TEXT,
    priority VARCHAR(20),
    status VARCHAR(20),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.assignments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emergency_id INTEGER NOT NULL UNIQUE
        REFERENCES public.emergencies(id) ON DELETE RESTRICT,
    ambulance_id INTEGER NOT NULL
        REFERENCES public.ambulances(id) ON DELETE RESTRICT,
    hospital_id INTEGER NOT NULL
        REFERENCES public.hospitals(id) ON DELETE RESTRICT,
    ambulance_eta INTEGER NOT NULL,
    hospital_eta INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.emergencies
    ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT NOW();
ALTER TABLE public.assignments
    ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT NOW();

